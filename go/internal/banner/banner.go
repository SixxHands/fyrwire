func Width() int {
	w := 0
	for _, l := range lines {
		if n := len([]rune(l)); n > w {
			w = n
		}
	}
	return w
}

const (
	flame = "\x1b[38;2;255;150;60m"
	dim   = "\x1b[38;2;120;130;140m"
	reset = "\x1b[0m"
)

func Render(colour bool) string {
	var b strings.Builder
	for _, l := range lines {
		if colour {
			b.WriteString(flame + l + reset + "\n")
		} else {
			b.WriteString(l + "\n")
		}
	}
	pad := (Width() - len([]rune(Tagline))) / 2
	if pad < 0 {
		pad = 0
	}
	b.WriteString(strings.Repeat(" ", pad))
	if colour {
		b.WriteString(dim + Tagline + reset)
	} else {
		b.WriteString(Tagline)
	}
	b.WriteString("\n")
	return b.String()
}
