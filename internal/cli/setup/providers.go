func chooseProvider() (string, string, string, int, error) {
	say("")
	say("%sWhere does your domain live?%s", text, reset)
	say("  %s1)%s Cloudflare  %s(free tier works)%s", dim, reset, dim, reset)
	say("  %s2)%s deSEC       %s(free, DNSSEC by default)%s", dim, reset, dim, reset)

	if strings.HasPrefix(ask("Which one", "1"), "2") {
		return setupDesec()
	}

	block, zone, tokenEnv, err := setupCloudflare()
	return block, zone, tokenEnv, 60, err
}

func setupCloudflare() (string, string, string, error) {
	say("")
	say("%sCloudflare%s", text, reset)

	token := readProviderToken(
		"FYRWIRE_CF_TOKEN",
		"dash.cloudflare.com -> My Profile -> API Tokens -> Edit zone DNS",
		"",
	)
	if token == "" {
		return "", "", "", model.Errorf("a token is required")
	}

	zones, err := detect.CloudflareZones(token)
	if err != nil {
		return "", "", "", err
	}
	if len(zones) == 0 {
		return "", "", "", model.Errorf("token sees no zones; give it Zone:DNS:Edit")
	}

	selected := pickCloudflareZone(zones)
	good("using %s", selected.Name)

	block := fmt.Sprintf("[provider]\ntype      = \"cloudflare\"\n"+
		"api_token = \"env:FYRWIRE_CF_TOKEN\"\nzone_id   = %q\n\n", selected.Id)
	return block, selected.Name, "FYRWIRE_CF_TOKEN", nil
}

func pickCloudflareZone(zones []detect.ZoneData) detect.ZoneData {
	if len(zones) == 1 {
		return zones[0]
	}

	say("  %szones this token can edit:%s", dim, reset)
	for i, zone := range zones {
		say("    %s%d)%s %s", dim, i+1, reset, zone.Name)
	}

	choice, _ := strconv.Atoi(ask("Which one", "1"))
	if choice >= 1 && choice <= len(zones) {
		return zones[choice-1]
	}

	return zones[0]
}

func setupDesec() (string, string, string, int, error) {
	say("")
	say("%sdeSEC%s", text, reset)

	token := readProviderToken(
		"FYRWIRE_DESEC_TOKEN",
		"desec.io -> Token management -> Create token",
		"scope the token with RRset policies and do not use your login token.",
	)
	if token == "" {
		return "", "", "", 0, model.Errorf("a token is required")
	}

	domains, err := detect.DesecDomains(token)
	if err != nil {
		return "", "", "", 0, err
	}
	if len(domains) == 0 {
		return "", "", "", 0, model.Errorf("token sees no domains; add your domain at desec.io first")
	}

	selected := pickDesecDomain(domains)
	good("using %s", selected.Name)

	minTtl, err := confirmDesecTtl(selected)
	if err != nil {
		return "", "", "", 0, err
	}

	block := fmt.Sprintf("[provider]\ntype   = \"desec\"\n"+
		"token  = \"env:FYRWIRE_DESEC_TOKEN\"\ndomain = %q\n\n", selected.Name)
	return block, selected.Name, "FYRWIRE_DESEC_TOKEN", minTtl, nil
}

func readProviderToken(envName, instructions, warning string) string {
	token := os.Getenv(envName)
	if token != "" {
		say("  %susing %s from environment%s", dim, envName, reset)
		return token
	}

	say("  %s%s%s", dim, instructions, reset)
	if warning != "" {
		note("%s", warning)
	}

	return ask("API token", "")
}

func confirmDesecTtl(selected detect.DomainData) (int, error) {
	minTtl := selected.MinimumTtl
	if minTtl == 0 {
		minTtl = 60
	}

	if minTtl > 60 {
		note("deSEC enforces a minimum TTL of %ds on %s (%d minutes cache on rotation).",
			minTtl, selected.Name, minTtl/60)
		if !askYesNo(fmt.Sprintf("Continue with a %ds TTL?", minTtl), true) {
			return 0, model.Errorf("stopped, nothing written")
		}
	}

	return minTtl, nil
}

func pickDesecDomain(domains []detect.DomainData) detect.DomainData {
	if len(domains) == 1 {
		return domains[0]
	}

	say("  %sdomains this token can edit:%s", dim, reset)
	for i, domain := range domains {
		say("    %s%d)%s %s", dim, i+1, reset, domain.Name)
	}

	choice, _ := strconv.Atoi(ask("Which one", "1"))
	if choice >= 1 && choice <= len(domains) {
		return domains[choice-1]
	}

	return domains[0]
}

func renderConfig(
	tokenEnv, sourceType, gateway, providerBlock, aName string,
	ttl int,
	services []serviceChoice,
) string {
	var builder strings.Builder
	builder.WriteString("# FyrWire config generated by `fyrwire setup`\n")
	fmt.Fprintf(&builder, "# Token is read from $%s.\n\n", tokenEnv)
	builder.WriteString("[fyrwire]\nversion = 1\n\n")

	if sourceType == "natpmp" {
		fmt.Fprintf(&builder, "[source]\ntype     = \"natpmp\"\ngateway  = %q\nlifetime = 120\n\n", gateway)
	} else {
		builder.WriteString("[source]\ntype    = \"command\"\n" +
			"host    = \"203.0.113.1\"\ncommand = \"echo 25565\"\n\n")
	}

	builder.WriteString(providerBlock)
	fmt.Fprintf(&builder, "[node]\na_name = %q\nttl    = %d\n\n", aName, ttl)

	for _, service := range services {
		fmt.Fprintf(&builder, "[[service]]\nname          = %q\n", service.name)
		if service.presetKey != "" {
			fmt.Fprintf(&builder, "preset        = %q\n", service.presetKey)
		}
		fmt.Fprintf(&builder, "internal_port = %d\nprotocol      = %q\nrecord        = %q\nsrv_name      = %q\n\n",
			service.internalPort, service.protocol, service.record, service.srvName)
	}

	builder.WriteString("[agent]\ninterval = 45\n")
	return builder.String()
}
