const (
	reset = "\x1b[0m"
	dim   = "\x1b[38;2;120;130;140m"
	ok    = "\x1b[38;2;110;220;150m"
	bad   = "\x1b[38;2;240;110;110m"
	warn  = "\x1b[38;2;240;190;90m"
	text  = "\x1b[38;2;235;235;235m"
)

var in = bufio.NewReader(os.Stdin)

func say(f string, a ...any)  { fmt.Printf(f+"\n", a...) }
func good(f string, a ...any) { say("  "+ok+"✓"+reset+" "+f, a...) }
func fail(f string, a ...any) { say("  "+bad+"✗"+reset+" "+f, a...) }
func note(f string, a ...any) { say("  "+warn+"!"+reset+" "+f, a...) }

func ask(prompt, def string) string {
	if def != "" {
		fmt.Printf("  %s [%s%s%s]: ", prompt, dim, def, reset)
	} else {
		fmt.Printf("  %s: ", prompt)
	}
	line, _ := in.ReadString('\n')
	line = strings.TrimSpace(line)
	if line == "" {
		return def
	}
	return line
}

func yes(prompt string, def bool) bool {
	d := "y/N"
	if def {
		d = "Y/n"
	}
	fmt.Printf("  %s [%s%s%s]: ", prompt, dim, d, reset)
	line, _ := in.ReadString('\n')
	line = strings.ToLower(strings.TrimSpace(line))
	if line == "" {
		return def
	}
	return strings.HasPrefix(line, "y")
}

type serviceChoice struct {
	name, presetKey, srvName, protocol, record string
	internalPort                               int
}

func Run(configPath string, force bool) error {
	if _, err := os.Stat(configPath); err == nil && !force {
		return model.Errorf(
			"%s already exists — pass --force to overwrite it, or use "+
				"`fyrwire add` to add a service", configPath)
	}
	fmt.Print(banner.Render(true))
	say("")

	say("%sFinding your gateway%s", text, reset)
	gateway, public, why := detect.FindGateway()
	sourceType := "natpmp"
	if gateway != "" {
		good("%s speaks NAT-PMP (%s)", gateway, why)
		good("your public address is %s", public)
	} else {
		fail("nothing answered NAT-PMP on any candidate")
		say("    %sThat usually means your VPN does not offer port forwarding,", dim)
		say("    it is off in the provider's settings, or your client exposes")
		say("    the port only through its own CLI.%s", reset)
		if yes("Read the port from a command instead?", true) {
			sourceType = "command"
		} else {
			gateway = ask("Gateway address to try anyway", "10.2.0.1")
		}
	}

	say("")
	say("%sWhere does your domain live?%s", text, reset)
	say("  %s1)%s Cloudflare  %s— free tier is fine%s", dim, reset, dim, reset)
	say("  %s2)%s deSEC       %s— free, non-profit, DNSSEC by default%s", dim, reset, dim, reset)
	var providerBlock, zoneName, tokenEnv string
	ttl := 60
	if strings.HasPrefix(ask("Which one", "1"), "2") {
		var err error
		providerBlock, zoneName, tokenEnv, ttl, err = setupDesec()
		if err != nil {
			return err
		}
	} else {
		var err error
		providerBlock, zoneName, tokenEnv, err = setupCloudflare()
		if err != nil {
			return err
		}
	}

	say("")
	say("%sWhat are you exposing?%s", text, reset)
	listening := map[int]bool{}
	for _, p := range detect.ListeningPorts() {
		listening[p.Port] = true
	}
	var services []serviceChoice
	for {
		key := ask("Preset (or `list`, or `custom`)", "minecraft")
		if key == "list" {
			printPresets()
			continue
		}
		p, found := preset.Get(key)
		if !found && key != "custom" {
			fail("no preset called %q — type `list` to see them", key)
			continue
		}
		var c serviceChoice
		if key == "custom" {
			c = askCustom(zoneName)
			if c.name == "" {
				continue
			}
		} else {
			c = serviceChoice{name: p.Key, presetKey: p.Key, protocol: p.Protocol,
				record: p.Record, internalPort: p.Port}
			c.internalPort = askPort(p, listening)
			label := ask("Subdomain players will use",
				strings.Split(zoneName, ".")[0])
			c.srvName = fmt.Sprintf("_%s._%s.%s.%s", p.Service, p.Protocol,
				label, zoneName)
		}

		switch p.Follows {
		case "srv-setup":
			note("%s reads the SRV record ONCE, when the server is added —", p.Label)
			say("    %sa later rotation breaks the saved entry.%s", dim, reset)
		case "manual":
			note("%s does not read SRV at all", p.Label)
			say("    %sThe A record still tracks your address; you hand out the", dim)
			say("    port yourself. Turn on the relay and it will at least always", dim)
			say("    be the same local service behind it.%s", reset)
		}
		if p.Note != "" {
			say("    %s%s%s", dim, p.Note, reset)
		}
		services = append(services, c)
		if !yes("Add another?", false) {
			break
		}
	}

	aName := ask("Name for THIS MACHINE's address record", "node."+zoneName)

	var b strings.Builder
	b.WriteString("# FyrWire — generated by `fyrwire setup`\n")
	fmt.Fprintf(&b, "# The token is read from $%s, so this file is safe to commit.\n\n",
		tokenEnv)
	b.WriteString("[fyrwire]\nversion = 1\n\n")
	if sourceType == "natpmp" {
		fmt.Fprintf(&b, "[source]\ntype     = \"natpmp\"\ngateway  = %q\nlifetime = 120\n\n",
			gateway)
	} else {
		b.WriteString("[source]\ntype    = \"command\"\n" +
			"host    = \"203.0.113.1\"   # or host_command\n" +
			"command = \"echo 25565\"    # must print host:port or a port\n\n")
	}
	b.WriteString(providerBlock)
	fmt.Fprintf(&b, "[node]\na_name = %q\nttl    = %d\n\n", aName, ttl)
	for _, s := range services {
		fmt.Fprintf(&b, "[[service]]\nname          = %q\n", s.name)
		if s.presetKey != "" {
			fmt.Fprintf(&b, "preset        = %q\n", s.presetKey)
		}
		fmt.Fprintf(&b, "internal_port = %d\nprotocol      = %q\n"+
			"record        = %q\nsrv_name      = %q\n\n",
			s.internalPort, s.protocol, s.record, s.srvName)
	}
	b.WriteString("[agent]\ninterval = 45\n")

	if err := os.MkdirAll(filepath.Dir(configPath), 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(configPath, []byte(b.String()), 0o644); err != nil {
		return err
	}
	say("")
	good("wrote %s", configPath)
	if os.Getenv(tokenEnv) == "" {
		note("export %s before running the agent:", tokenEnv)
		say("    %sexport %s=\"…\"%s", dim, tokenEnv, reset)
	}
	say("")
	say("  %sNext:%s", text, reset)
	say("    fyrwire once       %s— publish, and see what changed%s", dim, reset)
	say("    fyrwire install    %s— run it in the background%s", dim, reset)
	return nil
}

func askPort(p preset.PresetData, listening map[int]bool) int {
	def := strconv.Itoa(p.Port)
	if len(listening) > 0 && !listening[p.Port] {
		var open []int
		for k := range listening {
			open = append(open, k)
		}
		sort.Ints(open)
		if len(open) > 0 {

			say("    %snothing on :%d. Listening here: %v%s", dim, p.Port, open, reset)
		}
	}
	for {
		v := ask("Local port it listens on", def)
		n, err := strconv.Atoi(v)
		if err == nil && n > 0 && n < 65536 {
			return n
		}
		fail("%q is not a port", v)
	}
}

func askCustom(zone string) serviceChoice {
	name := ask("Service name (for your own reference)", "")
	if name == "" {
		return serviceChoice{}
	}
	label := ask("SRV service label (e.g. minecraft, http)", name)
	if err := preset.ValidateService(label); err != nil {
		fail("%v", err)
		return serviceChoice{}
	}
	proto := ask("Protocol (tcp/udp)", "tcp")
	if proto != "tcp" && proto != "udp" {
		fail("protocol must be tcp or udp")
		return serviceChoice{}
	}
	port, err := strconv.Atoi(ask("Local port", "0"))
	if err != nil || port <= 0 {
		fail("that is not a port")
		return serviceChoice{}
	}
	sub := ask("Subdomain", strings.Split(zone, ".")[0])
	return serviceChoice{name: name, protocol: proto, record: "srv",
		internalPort: port,
		srvName:      fmt.Sprintf("_%s._%s.%s.%s", label, proto, sub, zone)}
}

func printPresets() {
	for _, g := range preset.Groups {
		items := preset.ByGroup(g)
		if len(items) == 0 {
			continue
		}
		say("    %s%s%s", dim, strings.ToUpper(g), reset)
		for _, p := range items {
			mark := ok + "auto" + reset
			switch p.Follows {
			case "srv-setup":
				mark = warn + "once" + reset
			case "manual":
				mark = dim + "manual" + reset
			}
			say("      %-20s %-6d %-4s %s", p.Key, p.Port, p.Protocol, mark)
		}
	}
}

func setupCloudflare() (block, zone, tokenEnv string, err error) {
	say("")
	say("%sCloudflare%s", text, reset)
	token := os.Getenv("FYRWIRE_CF_TOKEN")
	if token != "" {
		say("  %susing FYRWIRE_CF_TOKEN from the environment%s", dim, reset)
	} else {
		say("  %sdash.cloudflare.com -> My Profile -> API Tokens ->", dim)
		say("  'Edit zone DNS' template. That is the only thing you need.%s", reset)
		token = ask("API token", "")
	}
	if token == "" {
		return "", "", "", model.Errorf("a token is required")
	}
	zones, err := detect.CloudflareZones(token)
	if err != nil {
		return "", "", "", err
	}
	if len(zones) == 0 {
		return "", "", "", model.Errorf(
			"that token cannot see any zones — re-create it with Zone:DNS:Edit")
	}
	pick := zones[0]
	if len(zones) > 1 {
		say("  %szones this token can edit:%s", dim, reset)
		for i, z := range zones {
			say("    %s%d)%s %s", dim, i+1, reset, z.Name)
		}
		n, _ := strconv.Atoi(ask("Which one", "1"))
		if n >= 1 && n <= len(zones) {
			pick = zones[n-1]
		}
	}
	good("using %s", pick.Name)
	return fmt.Sprintf("[provider]\ntype      = \"cloudflare\"\n"+
			"api_token = \"env:FYRWIRE_CF_TOKEN\"\nzone_id   = %q\n\n", pick.ID),
		pick.Name, "FYRWIRE_CF_TOKEN", nil
}

func setupDesec() (block, zone, tokenEnv string, ttl int, err error) {
	say("")
	say("%sdeSEC%s", text, reset)
	token := os.Getenv("FYRWIRE_DESEC_TOKEN")
	if token != "" {
		say("  %susing FYRWIRE_DESEC_TOKEN from the environment%s", dim, reset)
	} else {
		say("  %sdesec.io -> Token management -> Create token.%s", dim, reset)
		note("a deSEC token with no policy attached can write EVERY record")
		say("    %son your account — deSEC treats 'no policy' as full write", dim)
		say("    access, which is the opposite of most APIs. Scope it with")
		say("    RRset policies afterwards, and do NOT use your login token:")
		say("    it expires when unused and the agent will stop.%s", reset)
		token = ask("API token", "")
	}
	if token == "" {
		return "", "", "", 0, model.Errorf("a token is required")
	}
	domains, err := detect.DesecDomains(token)
	if err != nil {
		return "", "", "", 0, err
	}
	if len(domains) == 0 {
		return "", "", "", 0, model.Errorf(
			"that token can see no domains — add your domain at desec.io first")
	}
	pick := domains[0]
	if len(domains) > 1 {
		say("  %sdomains this token can edit:%s", dim, reset)
		for i, d := range domains {
			say("    %s%d)%s %s", dim, i+1, reset, d.Name)
		}
		n, _ := strconv.Atoi(ask("Which one", "1"))
		if n >= 1 && n <= len(domains) {
			pick = domains[n-1]
		}
	}
	good("using %s", pick.Name)

	minTTL := pick.MinimumTTL
	if minTTL == 0 {
		minTTL = 60
	}
	if minTTL > 60 {
		note("deSEC enforces a minimum TTL of %ds on %s", minTTL, pick.Name)
		say("    %sAfter a port rotation, a client that already looked the name", dim)
		say("    up can keep the OLD port cached for up to %d minutes.", minTTL/60)
		say("    Ports rotate on a lease lapse or a VPN reconnect, not")
		say("    constantly, so this is survivable — and deSEC grants")
		say("    lower-TTL exceptions on request.%s", reset)
		if !yes(fmt.Sprintf("Continue with a %ds TTL?", minTTL), true) {
			return "", "", "", 0, model.Errorf("stopped, nothing written")
		}
	}
	return fmt.Sprintf("[provider]\ntype   = \"desec\"\n"+
			"token  = \"env:FYRWIRE_DESEC_TOKEN\"\ndomain = %q\n\n", pick.Name),
		pick.Name, "FYRWIRE_DESEC_TOKEN", minTTL, nil
}
